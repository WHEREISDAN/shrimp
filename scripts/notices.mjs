#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the licenses of the Rust crates (cargo-about, configured in
// src-tauri/about.toml) and the JavaScript packages (pnpm licenses) that release builds ship,
// plus whisper.cpp, which whisper-rs-sys compiles in. Usage: pnpm notices
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const tauri = join(root, "src-tauri");
const run = (command, args, cwd) =>
  execFileSync(command, args, { cwd, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

const licenseFile = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

function licenseTexts(dir) {
  return readdirSync(dir)
    .filter((name) => licenseFile.test(name))
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").trim());
}

function rustSection() {
  return run("cargo", ["about", "generate", "about.hbs"], tauri).trim();
}

function whisperSection() {
  const metadata = JSON.parse(run("cargo", ["metadata", "--format-version", "1"], tauri));
  const sys = metadata.packages.find((p) => p.name === "whisper-rs-sys");
  if (!sys) throw new Error("whisper-rs-sys is not a dependency");
  const license = join(dirname(sys.manifest_path), "whisper.cpp", "LICENSE");
  if (!existsSync(license)) throw new Error(`no ${license}`);
  return [
    `### whisper.cpp and ggml (compiled in by whisper-rs-sys ${sys.version})`,
    "",
    "```text",
    readFileSync(license, "utf8").trim(),
    "```",
  ].join("\n");
}

function javascriptSection() {
  const byLicense = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"], root));
  const groups = new Map();
  for (const [license, packages] of Object.entries(byLicense)) {
    for (const pkg of packages) {
      pkg.versions.forEach((version, index) => {
        const texts = licenseTexts(pkg.paths[index]);
        const text = texts.length > 0 ? texts.join("\n\n") : `License: ${license}`;
        const group = groups.get(text) ?? { license, packages: [] };
        group.packages.push(`${pkg.name} ${version}`);
        groups.set(text, group);
      });
    }
  }
  return [...groups.entries()]
    .sort(([, a], [, b]) => a.packages[0].localeCompare(b.packages[0]))
    .map(([text, group]) =>
      [
        `### ${group.license}`,
        "",
        "Used by:",
        "",
        ...group.packages.sort().map((name) => `- ${name}`),
        "",
        "```text",
        text,
        "```",
      ].join("\n"),
    )
    .join("\n\n");
}

const notices = `# Third-party notices

Shrimp's release builds include the open-source software listed below. Each entry gives
the license text and the packages it covers. This file is generated by \`pnpm notices\`
(scripts/notices.mjs); don't edit it by hand.

Shrimp downloads Whisper speech models from Hugging Face at runtime; they are not part of
the app. The English word list in \`src-tauri/src/context/common_words.txt\` carries its own
license in \`common_words_license.txt\`.

## Rust crates

${rustSection()}

tauri-plugin-mcp 0.3.1 (https://github.com/P3GLEG/tauri-plugin-mcp, used only by
development builds) declares the MIT license in its package.json and publishes no license
file.

## Native libraries

${whisperSection()}

## JavaScript packages

${javascriptSection()}
`;

writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), notices.replace(/\r\n?/g, "\n"));
console.log("Wrote THIRD_PARTY_NOTICES.md");
