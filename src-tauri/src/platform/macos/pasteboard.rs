//! The general pasteboard: snapshot every item and type, write a transcript,
//! and restore the snapshot. Call from the main thread.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardTypeHTML, NSPasteboardTypeString,
    NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString};

use crate::platform::InsertText;

/// Clipboard managers skip entries carrying these markers (nspasteboard.org).
const TRANSIENT_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Every pasteboard item as (type, bytes) pairs, so text, rich text, images
/// and files all survive a restore.
#[derive(Debug, Default)]
pub struct Snapshot {
    items: Vec<Vec<(String, Vec<u8>)>>,
}

pub fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// The clipboard's plain text, if it has any.
pub fn read_text() -> Option<String> {
    NSPasteboard::generalPasteboard()
        .stringForType(unsafe { NSPasteboardTypeString })
        .map(|text| text.to_string())
}

pub fn snapshot() -> Snapshot {
    let pasteboard = NSPasteboard::generalPasteboard();
    let items = pasteboard
        .pasteboardItems()
        .map(|items| items.iter().map(|item| item_data(&item)).collect())
        .unwrap_or_default();
    Snapshot { items }
}

fn item_data(item: &NSPasteboardItem) -> Vec<(String, Vec<u8>)> {
    item.types()
        .iter()
        .filter_map(|kind| {
            let data = item.dataForType(&kind)?;
            Some((kind.to_string(), data.to_vec()))
        })
        .collect()
}

/// Replaces the clipboard with `text` (plain, plus HTML when given) and
/// returns the new change count.
pub fn write_text(text: &InsertText, transient: bool) -> isize {
    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    pasteboard.setString_forType(&NSString::from_str(&text.plain), unsafe {
        NSPasteboardTypeString
    });
    if let Some(html) = &text.html {
        pasteboard.setString_forType(&NSString::from_str(html), unsafe { NSPasteboardTypeHTML });
    }
    if transient {
        let empty = NSData::new();
        for kind in TRANSIENT_TYPES {
            pasteboard.setData_forType(Some(&empty), &NSString::from_str(kind));
        }
    }
    pasteboard.changeCount()
}

pub fn restore(snapshot: &Snapshot) {
    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = snapshot
        .items
        .iter()
        .filter(|types| !types.is_empty())
        .map(|types| {
            let item = NSPasteboardItem::new();
            for (kind, bytes) in types {
                item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind));
            }
            ProtocolObject::from_retained(item)
        })
        .collect();
    if !items.is_empty() {
        pasteboard.writeObjects(&NSArray::from_retained_slice(&items));
    }
}
